/** Serialisers for TXT / CSV / TSV / JSON exports. Pure functions, shared by web + CLI. */
import { wordCount } from './normalize.js';
import { classifyObservations, familyOfStrategy } from './classify.js';

/** Version tag of the evidence JSON; `afkrt oportunidades` only accepts this schema. */
export const EVIDENCE_SCHEMA = 'afkrt-br/evidencias@1';
export const EVIDENCE_NOTICE = 'hits / observations count how many times a phrase came back from the providers — they are NOT search volume. '
  + 'Submitted queries (query / generatedQuery) are generated by this program; only `phrase` values are observed suggestions.';

export const FORMATS = ['txt', 'csv', 'tsv', 'json', 'md'];

export const MIME = {
  txt: 'text/plain;charset=utf-8',
  csv: 'text/csv;charset=utf-8',
  tsv: 'text/tab-separated-values;charset=utf-8',
  json: 'application/json;charset=utf-8',
  md: 'text/markdown;charset=utf-8',
};

// Legacy columns (unchanged order, also the TSV layout) — seed/source_query/strategy/depth describe the FIRST observation.
const COLUMNS = ['keyword', 'engines', 'engine_count', 'hits', 'words', 'question', 'seed', 'source_query', 'strategy', 'depth'];
// Evidence columns appended to the CSV (one row per de-duplicated phrase, every origin kept).
const EVIDENCE_COLUMNS = ['origin_families', 'text_families', 'observations', 'distinct_requests', 'submitted_queries', 'seeds', 'providers', 'source_types',
  'hl', 'gl', 'runs', 'first_collected_at', 'last_collected_at', 'echo_of_query', 'cached_observations'];

const uniq = (a) => [...new Set(a.filter((x) => x !== undefined && x !== null && x !== ''))];
/** Chronological order (not lexicographic), so mixed time-zone offsets sort correctly. */
export const sortTimes = (list) => uniq(list).sort((a, b) => Date.parse(a) - Date.parse(b));
/** Observations of a record; legacy records (no observations) are described from their first-origin fields only. */
const obsOf = (r) => (Array.isArray(r.observations) ? r.observations : []);
// Search languages of a record (none = unknown -> language-agnostic classification).
const langsOf = (r, meta) => { const l = uniq(obsOf(r).map((x) => x.hl)); return l.length ? l : meta?.lang ? [meta.lang] : []; };
const originFamilies = (r) => {
  const o = obsOf(r);
  if (!o.length) return r.strategy ? [familyOfStrategy(r.strategy)] : [];
  return uniq(o.flatMap((x) => (x.origins?.length ? x.origins.map((y) => y.family) : [x.originFamily])));
};
// Each (language, run) of a record is classified with that run's own terms (meta.familyTermsByRun), else the export's terms.
const textFamilies = (r, meta) => classifyObservations(r.keyword, obsOf(r), meta?.familyTermsByRun || null, meta?.familyTerms, langsOf(r, meta)[0] || null);
const questionOf = (r, meta) => textFamilies(r, meta).includes('perguntas');

const row = (r, meta) => [
  r.keyword,
  (r.engines || []).join('|'),
  (r.engines || []).length,
  r.hits ?? 1,
  wordCount(r.keyword),
  questionOf(r, meta) ? 'yes' : 'no',
  r.seed ?? '',
  r.query ?? '',
  r.strategy ?? '',
  r.depth ?? 0,
];

const evidenceRow = (r, meta) => {
  const o = obsOf(r);
  const times = sortTimes(o.map((x) => x.collectedAt));
  return [
    originFamilies(r).join('|'),
    textFamilies(r, meta).join('|'),
    o.length,
    uniq(o.map((x) => x.requestId)).length,
    uniq(o.map((x) => x.query)).join(' | '),
    uniq(o.flatMap((x) => (x.origins?.length ? x.origins.map((y) => y.seed) : [x.seed]))).join(' | '),
    uniq(o.map((x) => x.provider)).join('|'),
    uniq(o.map((x) => x.sourceType)).join('|'),
    uniq(o.map((x) => x.hl)).join('|'),
    uniq(o.map((x) => x.gl)).join('|'),
    uniq(o.map((x) => x.runId)).length,
    times[0] || '',
    times.at(-1) || '',
    o.some((x) => x.echoOfQuery) ? 'yes' : 'no',
    o.filter((x) => x.fromCache === true).length,
  ];
};

/** CSV cell with spreadsheet formula-injection guard (also used by the opportunities CSV). */
export const csvCell = (v) => {
  const s = String(v ?? '');
  // Guard against CSV/formula injection in spreadsheet apps.
  const safe = /^[=+\-@\t\r]/.test(s) ? `'${s}` : s;
  return /[",\n\r]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
};
const tsvCell = (v) => String(v ?? '').replace(/[\t\r\n]+/g, ' ');

export function toTXT(records) { return records.map((r) => r.keyword).join('\n') + (records.length ? '\n' : ''); }

export function toCSV(records, meta = {}) {
  // BOM so Excel opens UTF-8 (Portuguese accents, Turkish, Chinese, Cyrillic…) correctly.
  const head = [...COLUMNS, ...EVIDENCE_COLUMNS].join(',');
  return '\uFEFF' + [head, ...records.map((r) => [...row(r, meta), ...evidenceRow(r, meta)].map(csvCell).join(','))].join('\r\n') + '\r\n';
}

export function toTSV(records, meta = {}) {
  return [COLUMNS.join('\t'), ...records.map((r) => row(r, meta).map(tsvCell).join('\t'))].join('\n') + '\n';
}

/** Runs present in the records (so the metadata never pretends the last batch describes every result). */
export function runsOf(records) {
  const runs = new Map();
  for (const r of records) for (const o of obsOf(r)) {
    const x = runs.get(o.runId) || { runId: o.runId, hl: new Set(), gl: new Set(), providers: new Set(), first: o.collectedAt, last: o.collectedAt, observations: 0 };
    x.hl.add(o.hl); x.gl.add(o.gl); x.providers.add(o.provider); x.observations += 1;
    if (Date.parse(o.collectedAt) < Date.parse(x.first)) x.first = o.collectedAt;
    if (Date.parse(o.collectedAt) > Date.parse(x.last)) x.last = o.collectedAt;
    runs.set(o.runId, x);
  }
  return [...runs.values()].map((x) => ({ runId: x.runId, hl: [...x.hl], gl: [...x.gl], providers: [...x.providers], firstCollectedAt: x.first, lastCollectedAt: x.last, observations: x.observations }));
}

export function toJSON(records, meta = {}) {
  return JSON.stringify({
    schema: EVIDENCE_SCHEMA,
    tool: 'Advanced Free Keyword Research Tool',
    generatedAt: new Date().toISOString(),
    notice: EVIDENCE_NOTICE,
    ...meta,
    runs: runsOf(records),
    count: records.length,
    keywords: records.map((r) => ({
      keyword: r.keyword, engines: r.engines, hits: r.hits, words: wordCount(r.keyword),
      question: questionOf(r, meta), seed: r.seed, sourceQuery: r.query, strategy: r.strategy, depth: r.depth,
      originFamilies: originFamilies(r), textFamilies: textFamilies(r, meta),
      observations: obsOf(r),
    })),
  }, null, 2);
}

export function toMarkdown(records) {
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  return ['| # | Keyword | Engines | Hits |', '|---|---|---|---|',
    ...records.map((r, i) => `| ${i + 1} | ${esc(r.keyword)} | ${esc((r.engines || []).join(', '))} | ${r.hits ?? 1} |`)].join('\n') + '\n';
}

export function serialize(format, records, meta) {
  switch (format) {
    case 'txt': return toTXT(records);
    case 'csv': return toCSV(records, meta);
    case 'tsv': return toTSV(records, meta);
    case 'json': return toJSON(records, meta);
    case 'md': return toMarkdown(records);
    default: throw new Error(`Unknown format: ${format}`);
  }
}

export function fileName(seeds, format) {
  const base = (seeds?.[0] || 'keywords').toLocaleLowerCase().replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-|-$/g, '').slice(0, 40) || 'keywords';
  const stamp = new Date().toISOString().slice(0, 16).replace(/[:T]/g, '-');
  // Non-spreadsheet downloads get a "coleta-" prefix so the .gitignore patterns catch them in any folder.
  const prefix = ['csv', 'tsv'].includes(format) ? '' : 'coleta-';
  return `${prefix}${base}${seeds?.length > 1 ? `-and-${seeds.length - 1}-more` : ''}-${stamp}.${format}`;
}
